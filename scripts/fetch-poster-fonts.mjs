/**
 * Vendors the fonts the office can choose for a poster's name and designation
 * into public/fonts/poster/, and writes the list the panel, the renderer and
 * the server all read: src/lib/posterFonts.js.
 *
 * Self-hosted for the same reason as the site's own fonts (scripts/fetch-fonts.py):
 * the CSP is font-src 'self', and a poster drawn before a third-party font
 * arrives is drawn in the wrong face. Every font here is from Google Fonts
 * under the SIL Open Font License.
 *
 * TELUGU faces are fetched with their Latin, so an English name on a poster
 * set in that face still matches. ENGLISH faces are Latin only: on a poster
 * they are listed first and the Telugu falls through to the Telugu face — one
 * line can carry both scripts, each in its own font.
 *
 * Run:  node scripts/fetch-poster-fonts.mjs   (output is committed)
 */
