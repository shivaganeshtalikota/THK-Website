async function faces(family, weight, subsets) {
  const fam = `${family.replace(/ /g, '+')}${weight === 400 ? '' : `:wght@${weight}`}`
  const css = await (await fetch(`https://fonts.googleapis.com/css2?family=${fam}&display=swap`, { headers: { 'User-Agent': UA } })).text()
  const out = []
  for (const m of css.matchAll(/\/\* ([a-z-]+) \*\/\s*@font-face\s*\{([^}]*)\}/g)) {
    const [, subset, body] = m
    if (!subsets.includes(subset)) continue
    const url = body.match(/url\((https:[^)]+\.woff2)\)/)?.[1]
    const range = body.match(/unicode-range:\s*([^;]+);/)?.[1].trim()
    if (url && range) out.push({ subset, url, range })
  }
  if (!out.length) throw new Error(`${family}: no faces`)
  return out
}

mkdirSync(OUT, { recursive: true })
const list = []
let bytes = 0
for (const [script, rows] of [['te', TELUGU], ['en', ENGLISH]]) {
  for (const [id, family, weight, label, note] of rows) {
    const got = await faces(family, weight, script === 'te' ? ['telugu', 'latin'] : ['latin'])
    const files = []
    for (const f of got) {
      const buf = Buffer.from(await (await fetch(f.url, { headers: { 'User-Agent': UA } })).arrayBuffer())
      const name = `${id}-${f.subset}.woff2`
      writeFileSync(join(OUT, name), buf)
      bytes += buf.length
      files.push({ src: `/fonts/poster/${name}`, range: f.range })
    }
    list.push({ id, script, label, note, family: `THK ${label}`, weight, files })
    console.log(`  ${id.padEnd(22)} ${files.map((f) => f.src.split('/').pop()).join(', ')}`)
  }
}

